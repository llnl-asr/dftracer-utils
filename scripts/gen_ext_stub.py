"""Write docs/source/_ext_stub.py, the stand-in for the native extension that
the docs build installs when the extension is not built, from
python/dftracer/utils/dftracer_utils_ext.pyi.

The stub holds every class, function and constant the .pyi declares and
nothing else: an attribute the .pyi does not declare is an AttributeError, as
it is on the compiled module. Class and function source is copied from the
.pyi unchanged, except that the last overload of a name loses its `@overload`.

    python scripts/gen_ext_stub.py          # rewrite the stub
    python scripts/gen_ext_stub.py --check  # exit 1 when the stub is stale

tests/python/test_ext_stub.py runs the check.
"""

import argparse
import ast
import sys
from pathlib import Path
from typing import Dict, List

ROOT = Path(__file__).resolve().parents[1]
PYI = ROOT / "python" / "dftracer" / "utils" / "dftracer_utils_ext.pyi"
STUB = ROOT / "docs" / "source" / "_ext_stub.py"

HEADER = '''# SPDX-License-Identifier: MIT
# Generated by scripts/gen_ext_stub.py from python/dftracer/utils/
# dftracer_utils_ext.pyi. Do not edit; run `python scripts/gen_ext_stub.py`.
"""Stand-in for the native ``dftracer_utils_ext`` module.

The docs build installs it with :func:`install_extension_stub` when the
extension is not built, so the Python package imports and autodoc reads it.
It declares what the .pyi declares: the classes, functions and constants, with
no behavior.
"""

from __future__ import annotations

import sys
import types
from typing import Generic, Tuple, TypedDict, TypeVar, overload
'''

FOOTER = '''

def install_extension_stub() -> None:
    """Install the stand-in as ``dftracer.utils.dftracer_utils_ext``."""
    ext_name = "dftracer.utils.dftracer_utils_ext"
    if ext_name in sys.modules:
        return
    ext = types.ModuleType(ext_name)
    for name in _EXPORTS:
        obj = globals()[name]
        if isinstance(obj, (type, types.FunctionType)):
            obj.__module__ = ext_name
        setattr(ext, name, obj)
    sys.modules[ext_name] = ext
'''

# The functions the Python package calls at import: their stub runs this code
# in place of the .pyi's `...`.
BODIES: Dict[str, str] = {
    "_api_rows": '''def _api_rows() -> Tuple[Tuple[str, str, str, str, str, str, bool, Tuple[str, ...], str, str], ...]:
    """The rows of api.def, read from the file the native module compiles in."""
    import importlib.util
    from pathlib import Path

    path = Path(__file__).resolve().parents[2] / "scripts" / "api_def.py"
    spec = importlib.util.spec_from_file_location("api_def", path)
    assert spec is not None and spec.loader is not None
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return tuple(tuple(row) for row in module.rows())''',
}

CONSTANT_DEFAULTS: Dict[str, str] = {"int": "0", "float": "0.0", "str": '""', "bool": "False"}


def _is_overload(node: ast.FunctionDef) -> bool:
    return any(isinstance(d, ast.Name) and d.id == "overload" for d in node.decorator_list)


def _span(node: ast.AST) -> range:
    first = min([node.lineno] + [d.lineno for d in getattr(node, "decorator_list", [])])
    return range(first, node.end_lineno + 1)


def _function_lines(group: List[ast.FunctionDef], lines: List[str]) -> List[str]:
    """The source of one name's definitions: every overload, the last without
    its `@overload` so the name is a plain function, or the lone def."""
    out: List[str] = []
    for node in group:
        drop = set()
        if node is group[-1]:
            drop = {
                d.lineno
                for d in node.decorator_list
                if isinstance(d, ast.Name) and d.id == "overload"
            }
        out += [lines[i - 1] for i in _span(node) if i not in drop]
    return out


def _body_lines(body: List[ast.stmt], lines: List[str]) -> List[str]:
    out: List[str] = []
    i = 0
    while i < len(body):
        node = body[i]
        if isinstance(node, ast.FunctionDef):
            group = [node]
            while _is_overload(group[-1]) and i + 1 < len(body):
                nxt = body[i + 1]
                if not (isinstance(nxt, ast.FunctionDef) and nxt.name == node.name):
                    break
                group.append(nxt)
                i += 1
            out += _function_lines(group, lines)
        elif isinstance(node, (ast.Expr, ast.AnnAssign, ast.Assign)):
            out += [lines[j - 1] for j in _span(node)]
        else:
            raise ValueError(f"line {node.lineno}: a {type(node).__name__} in a class body")
        i += 1
    return out


def _class_lines(node: ast.ClassDef, lines: List[str]) -> List[str]:
    first = node.body[0]
    if first.lineno == node.lineno:
        return [lines[i - 1] for i in _span(node)]
    header = [lines[i - 1] for i in range(node.lineno, first.lineno)]
    return header + _body_lines(node.body, lines)


def _typevar_line(node: ast.Assign) -> str:
    call = node.value
    assert isinstance(call, ast.Call) and isinstance(call.func, ast.Name)
    keep = [
        f"{k.arg}={ast.literal_eval(k.value)}"
        for k in call.keywords
        if k.arg in ("covariant", "contravariant")
    ]
    name = node.targets[0].id  # type: ignore[attr-defined]
    return f"{name} = TypeVar({', '.join([repr(name)] + keep)})"


def build(pyi: str) -> str:
    lines = pyi.split("\n")
    tree = ast.parse(pyi)
    blocks: List[List[str]] = []
    exports: List[str] = []
    body = tree.body
    i = 0
    while i < len(body):
        node = body[i]
        if isinstance(node, ast.ClassDef):
            blocks.append(_class_lines(node, lines))
            exports.append(node.name)
        elif isinstance(node, ast.FunctionDef):
            group = [node]
            while _is_overload(group[-1]) and i + 1 < len(body):
                nxt = body[i + 1]
                if not (isinstance(nxt, ast.FunctionDef) and nxt.name == node.name):
                    break
                group.append(nxt)
                i += 1
            blocks.append(
                BODIES[node.name].split("\n")
                if node.name in BODIES
                else _function_lines(group, lines)
            )
            exports.append(node.name)
        elif (
            isinstance(node, ast.Assign)
            and isinstance(node.value, ast.Call)
            and isinstance(node.value.func, ast.Name)
            and node.value.func.id == "TypeVar"
        ):
            blocks.append([_typevar_line(node)])
            exports.append(node.targets[0].id)  # type: ignore[attr-defined]
        elif isinstance(node, ast.AnnAssign) and node.value is None:
            target = node.target
            assert isinstance(target, ast.Name)
            annotation = ast.get_source_segment(pyi, node.annotation)
            default = CONSTANT_DEFAULTS.get(annotation or "", "()")
            blocks.append([f"{target.id}: {annotation} = {default}"])
            exports.append(target.id)
        i += 1
    parts = [HEADER]
    for block in blocks:
        parts.append("\n".join(block))
    parts.append("_EXPORTS = (\n" + "".join(f'    "{n}",\n' for n in exports) + ")")
    return "\n\n\n".join(parts) + "\n" + FOOTER


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    new = build(PYI.read_text(encoding="utf-8"))
    old = STUB.read_text(encoding="utf-8") if STUB.exists() else ""
    if args.check:
        if new != old:
            print(f"stale: {STUB.name} (run python scripts/gen_ext_stub.py)", file=sys.stderr)
            return 1
        return 0
    if new != old:
        STUB.write_text(new, encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())
