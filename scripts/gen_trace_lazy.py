"""Generate python/dftracer/utils/trace/_lazy.py.

The file holds one typed delegate on TraceViewer for each LazyFrame method that
TraceViewer does not define itself: the method runs on ``self.lazy()`` and
returns a plain LazyFrame. Add or change a LazyFrame method, or a TraceViewer
override of one, then regenerate from the repository root:

    python scripts/gen_trace_lazy.py

``--out PATH`` writes elsewhere. The text is formatted with ruff through uvx,
exactly as the committed file is, and tests/python/test_trace_lazy_generated.py
compares the two.
"""

import argparse
import ast
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
PKG = ROOT / "python" / "dftracer" / "utils"


def generate() -> str:
    root = str(PKG) + "/"
    lsrc = open(root + "_lazyframe.py").read()
    lt = ast.parse(lsrc)
    tsrc = open(root + "trace/_viewer.py").read()
    tt = ast.parse(tsrc)
    lc = [n for n in lt.body if isinstance(n, ast.ClassDef) and n.name == "LazyFrame"][0]
    tc = [n for n in tt.body if isinstance(n, ast.ClassDef) and n.name == "TraceViewer"][0]
    tvn = {n.name for n in tc.body if isinstance(n, ast.FunctionDef)}
    keep_priv = {"__arrow_c_stream__", "__getitem__"}

    def want(n):
        return n not in tvn and (not n.startswith("_") or n in keep_priv)

    out = []
    for node in lc.body:
        if not isinstance(node, ast.FunctionDef) or not want(node.name):
            continue
        decos = [ast.unparse(d) for d in node.decorator_list]
        a = node.args
        parts = []
        for p in a.posonlyargs + a.args:
            if p.arg != "self":
                parts.append(p.arg)
        if a.vararg:
            parts.append("*" + a.vararg.arg)
        for p in a.kwonlyargs:
            parts.append(f"{p.arg}={p.arg}")
        if a.kwarg:
            parts.append("**" + a.kwarg.arg)
        sig = ast.unparse(a)
        ret = " -> " + ast.unparse(node.returns) if node.returns else ""
        lines = []
        for d in decos:
            lines.append("    @" + d)
        lines.append(
            f"    def {node.name}({sig}){ret}:"
            if "overload" not in decos
            else f"    def {node.name}({sig}){ret}: ..."
        )
        if "overload" in decos:
            out.append("\n".join(lines))
            continue
        doc = ast.get_docstring(node, clean=False)
        if doc is not None and isinstance(node.body[0], ast.Expr):
            seg = ast.get_source_segment(lsrc, node.body[0])
            lines.append("        " + seg)
        if "property" in decos:
            lines.append(f"        return self.lazy().{node.name}")
        elif node.name == "__getitem__":
            lines.append("        return self.lazy()[key]")
        elif node.name == "__arrow_c_stream__":
            lines.append(f"        return self.lazy().__arrow_c_stream__({', '.join(parts)})")
        else:
            lines.append(f"        return self.lazy().{node.name}({', '.join(parts)})")
        out.append("\n".join(lines))
    # imports from _lazyframe.py
    imports = []
    for n in lt.body:
        if isinstance(n, (ast.Import, ast.ImportFrom)) and not (
            isinstance(n, ast.ImportFrom) and n.module == "__future__"
        ):
            imports.append(ast.get_source_segment(lsrc, n))
        if isinstance(n, ast.If) and "TYPE_CHECKING" in ast.unparse(n.test):
            imports.append(ast.get_source_segment(lsrc, n))
    header = (
        "# SPDX-License-Identifier: MIT\n"
        '"""The :class:`~dftracer.utils.LazyFrame` operations that a\n'
        ":class:`~dftracer.utils.trace.TraceViewer` takes without keeping its own type: each\n"
        "runs on the viewer's plan (:meth:`TraceViewer.lazy`) and returns a plain\n"
        '``LazyFrame``. Generated by scripts/gen_trace_lazy.py; do not edit."""\n\n'
        "from __future__ import annotations\n\n"
    )
    body = "\n".join(imports)
    body = body.replace("from . import dftracer_utils_ext as _ext\n", "")
    body = re.sub(r"^(\s*)from \.(\w)", r"\1from ..\2", body, flags=re.M)
    text = (
        header
        + "from .. import dftracer_utils_ext as _ext\n"
        + body
        + "\n\nif TYPE_CHECKING:\n    from .._lazyframe import LazyFrame, SinkSummary, Value\n\n\nclass LazyOps(_ext.TraceViewer):\n    __slots__ = ()\n\n"
        + "\n\n".join(out)
        + "\n"
    )

    return text


def ruff(text: str) -> str:
    name = "python/dftracer/utils/trace/_lazy.py"
    for args in (
        ["check", "--fix", "--select", "F401,I001", "--stdin-filename", name, "-"],
        ["format", "--stdin-filename", name, "-"],
    ):
        run = subprocess.run(
            ["uvx", "ruff", *args], input=text, capture_output=True, text=True, cwd=ROOT
        )
        if run.returncode not in (0, 1) or not run.stdout:
            sys.exit(run.stderr)
        text = run.stdout
    return text


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("--out", type=Path, default=PKG / "trace" / "_lazy.py")
    args = parser.parse_args()
    args.out.write_text(ruff(generate()), encoding="utf-8")


if __name__ == "__main__":
    main()
